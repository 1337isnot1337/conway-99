"""Source-bound read-only review of the shifted integer-population family."""
import argparse
import ast
import gzip
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = "experiments/workspace/root_prism_free_f0_orbit_integer_quadratics.py"
SOURCE_SHA = "527e4b52be8bd5d2efaede2c55c2bf6c100e65066dad735924df644a1a14a0a4"
PREPARATION = "experiments/logs/root-prism-free/f0-orbit-integer-quadratics-preparation01.json.gz"
PREPARATION_SHA = "9c12695392afa42019cc365326645863d704ad10ffce6c77443236ca3edf72be"


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    assert not args.output.exists()
    raw = (ROOT / SOURCE).read_bytes()
    assert digest(raw) == SOURCE_SHA
    tree = ast.parse(raw)
    names = [n.name for n in tree.body if isinstance(n, ast.FunctionDef)]
    assert names == ["sha", "canonical", "read_input", "save_new", "load_record", "normalized", "row_key", "form_list", "controls", "prepare_data", "make_row", "scan", "main"]
    preparation_raw = (ROOT / PREPARATION).read_bytes()
    assert digest(preparation_raw) == PREPARATION_SHA
    prep = json.loads(gzip.decompress(preparation_raw))
    assert prep["source_sha256"] == SOURCE_SHA
    assert prep["forms_count"] == 1764
    assert prep["family_counts"] == {"single": 42, "union": 861, "difference": 861}
    assert len(prep["pair_population_blocks"]) == 903
    assert prep["literal_pair_coverage"] == 114960 and prep["retained_pair_orbits"] == 9353
    assert prep["old_fixed_zero_pair_orbits"] == 389
    assert prep["graph_automorphism_assumed"] is False
    assert prep["single_graph_block_rank_one_constraints_imposed"] is False
    report = {
        "status": "PASS: complete mathematical and source review of shifted integer orbit populations",
        "review_source_sha256": digest(Path(__file__).read_bytes()),
        "subject_source": {"path": SOURCE, "sha256": SOURCE_SHA},
        "preparation": {"path": PREPARATION, "sha256": PREPARATION_SHA},
        "complete_subject_functions_read": names,
        "mathematical_findings": [
            "For every Boolean selector assignment and integer signed population L, (L-k)(L-k-1) is nonnegative for every integer k. Core-group averaging preserves this inequality without assuming a graph automorphism.",
            "The diagonal square uses z_a squared equals z_a. Distinct pair products have factor2 before the exact division by2. The within-orbit block is the unordered-pair sum, while the cross-orbit block counts each distinct pair once.",
            "For positive orbit i and negative orbit j the implemented row is k*N_i-(k+1)*N_j-B_ii-B_jj+B_ij <= k*(k+1)/2. Both the sign and the integer division are correct for every integer k, including negative k.",
            "For a fixed mean m and second moment, k=floor(m) minimizes k*(k+1)-(2*k+1)*m over all integer k. At integral m there are two adjacent minimizers; the chosen one is sufficient.",
            "All903 orbit blocks cover the114960 literal pairs. Dropping exactly389 certified-zero pair coordinates preserves the expansion, and all9353 retained pair coordinates remain represented.",
            "The proposal is decoded as exact dyadic rationals. The stored gap is checked against the literal population quadratic, not accepted from a floating sign.",
            "Positive-gcd normalization preserves inequality orientation. Both signs of parent equalities are indexed, while inequalities retain their original sign. Literal-row duplicate detection does not claim implication completeness or strict strengthening.",
            "Scan preparation is fully regenerated by cold replay. The old path proposal is expressly not claimed feasible for the current parent, and a valid cut does not require that claim."
        ],
        "family_scope": "Complete42 single,861 union and861 oriented-difference forms, with all integer shifts minimized exactly for the chosen proposal. No larger population family or nonlinear rank-one identity is imposed.",
        "subject_imported": False, "controls_repeated": False,
        "domain_or_block_census_repeated": False, "proposal_evaluated": False,
        "optimizer_calls": 0, "eigendecompositions": 0,
        "retained_cut_count_or_gap_audited": False,
    }
    args.output.write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps(report, indent=2), flush=True)


if __name__ == "__main__":
    main()

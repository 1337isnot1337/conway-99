"""Exact small-type2-vertex spectral reduction for seven all-red grids.

The residual graph has degree3 on Y and degree1 outside Y. Its restriction
to Y is a triangle-free subcubic graph; all other components are pendant
leaves and isolated edges. For |Y|<=6 the core census is checked against
every labeled graph, independently of the graph-atlas representative list.
"""

import argparse
from collections import Counter
from itertools import combinations, permutations
import json
from pathlib import Path

import networkx as nx
import sympy as sp

from red_grid_cubic_trace import companion_traces


X = sp.Symbol('x')


def cores(size):
    if size == 0:
        return [(-1, [])], {'labeled_graphs': 1, 'unlabeled_cores': 1}
    pairs = list(combinations(range(size), 2))
    pair_index = {pair:i for i,pair in enumerate(pairs)}
    valid = set()
    for mask in range(1 << len(pairs)):
        neighbors = [0]*size
        for bit,(a,b) in enumerate(pairs):
            if mask >> bit & 1:
                neighbors[a] |= 1 << b
                neighbors[b] |= 1 << a
        if max(map(int.bit_count,neighbors), default=0) > 3:
            continue
        if any(neighbors[a] & neighbors[b] for bit,(a,b) in enumerate(pairs) if mask >> bit & 1):
            continue
        valid.add(mask)
    representatives = []
    covered = set()
    for index,G in enumerate(nx.graph_atlas_g()):
        if len(G) != size or max(dict(G.degree()).values(), default=0) > 3:
            continue
        if any(nx.triangles(G).values()):
            continue
        edges = list(G.edges())
        orbit = {sum(1 << pair_index[tuple(sorted((p[a],p[b])))] for a,b in edges)
                 for p in permutations(range(size))}
        assert not (orbit & covered)
        assert orbit <= valid
        covered |= orbit
        representatives.append((index,edges))
    assert covered == valid
    return representatives, {'labeled_graphs': len(valid), 'unlabeled_cores': len(representatives)}


def matrix(size, edges):
    D = [[0]*36 for _ in range(36)]
    degrees = [0]*size
    for a in range(size):
        D[a][a] = 1
    for a,b in edges:
        D[a][b] = D[b][a] = 1
        degrees[a] += 1
        degrees[b] += 1
    next_vertex = size
    for a in range(size):
        for _ in range(3-degrees[a]):
            D[a][next_vertex] = D[next_vertex][a] = 1
            next_vertex += 1
    assert next_vertex <= 36 and (36-next_vertex) % 2 == 0
    for a in range(next_vertex,36,2):
        D[a][a+1] = D[a+1][a] = 1
    assert all(sum(row) == (4 if i < size else 1) for i,row in enumerate(D))
    return D


def factor_information(D, use_krylov=True):
    polynomial = sp.Matrix(D).charpoly(X).as_poly()
    factors = [(sp.Poly(f,X),int(m)) for f,m in sp.factor_list(polynomial)[1]]
    squarefree = sp.Poly(1,X)
    for f,m in factors:
        squarefree *= f
    support = [[j for j,value in enumerate(row) if value] for row in D]
    answer = []
    for f,m in factors:
        # g(D)1 is the projection onto the f-spectral summand, up to an
        # invertible factor there. Nonzero means the rational Krylov space
        # generated by1 consumes one full copy of f.
        g = squarefree.exquo(f)
        vector = [0]*36
        for coefficient in g.all_coeffs():
            vector = [sum(vector[j] for j in row)+int(coefficient) for row in support]
        removed = int(any(vector)) if use_krylov else 0
        available = m-removed
        outside_interval = bool(f.eval(3) == 0 or f.count_roots(3,sp.oo))
        coefficients = list(map(int,f.all_coeffs()))
        degree,s1,s2,s3 = companion_traces(coefficients)
        energy = 12*degree-s1-s2
        if not outside_interval:
            assert energy > 0
        answer.append({'polynomial': coefficients, 'multiplicity': m,
                       'krylov_multiplicity_removed': removed,
                       'available': 0 if outside_interval else available,
                       'outside_allowed_interval': outside_interval,
                       'statistics': [degree,s1,s2,s3,energy]})
    return answer


def spectra(size, information, cubic=True):
    data = [row for row in information if row['available']]
    answer = []
    required = 32-4*size//3
    def visit(index,rank,s1,s2,s3,energy,chosen):
        if energy > 112 or rank > 28:
            return
        if index == len(data):
            if energy != 112 or (140-3*rank+s1) % 7:
                return
            p = (140-3*rank+s1)//7
            if not 0 <= p <= 28-rank:
                return
            if cubic and s3+s2-12*s1 != required:
                return
            answer.append({'rank': rank, 'trace': s1, 'trace_square': s2,
                           'trace_cube': s3, 'cubic_left_side': s3+s2-12*s1,
                           'cubic_required': required,
                           'kernel_positive_multiplicity': p,
                           'factors': [{'polynomial': c, 'multiplicity': m} for c,m in chosen if m]})
            return
        row = data[index]
        d,t1,t2,t3,e = row['statistics']
        for m in range(min(row['available'],(112-energy)//e)+1):
            visit(index+1,rank+m*d,s1+m*t1,s2+m*t2,s3+m*t3,energy+m*e,
                  chosen+[(row['polynomial'],m)])
    visit(0,0,0,0,0,0,[])
    return answer


def run(sizes, output=None):
    results = []
    for size in sizes:
        representatives,audit = cores(size)
        rows = []
        for atlas,edges in representatives:
            D = matrix(size,edges)
            info = factor_information(D)
            before = spectra(size,info,False)
            after = spectra(size,info,True)
            rows.append({'atlas_index': atlas, 'edges': [list(e) for e in edges],
                         'factor_information': info, 'quadratic_spectrum_count': len(before),
                         'cubic_spectrum_count': len(after), 'cubic_spectra': after})
        summary = {'type2_vertices': size, 'core_census': audit,
                   'quadratic_surviving_cores': sum(bool(row['quadratic_spectrum_count']) for row in rows),
                   'cubic_surviving_cores': sum(bool(row['cubic_spectrum_count']) for row in rows),
                   'cubic_spectra': sum(row['cubic_spectrum_count'] for row in rows)}
        print(json.dumps(summary), flush=True)
        results.append({**summary,'cores': rows})
    result = {'cases': results}
    if output:
        Path(output).parent.mkdir(parents=True,exist_ok=True)
        Path(output).write_text(json.dumps(result,indent=2)+'\n')
    return result


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--sizes',type=int,nargs='+',default=[0,3,6],choices=[0,3,6])
    parser.add_argument('--output')
    args = parser.parse_args()
    run(args.sizes,args.output)
